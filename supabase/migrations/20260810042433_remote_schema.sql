CREATE FUNCTION public.increment_app_counter (
  counter_key text
)
  RETURNS bigint
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path TO 'public'
  AS $function$
  insert into app_counters (key, value)
  values (counter_key, 1)
  on conflict (key) do update set value = app_counters.value + 1
  returning value;
$function$;

