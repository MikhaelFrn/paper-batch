   FROM public.lists
  WHERE ((lists.id = list_items.list_id) AND (lists.owner_id = auth.uid())))) OR (EXISTS ( SELECT 1
   FROM public.list_members
  WHERE
    ((list_members.list_id = list_items.list_id) AND (list_members.user_id = auth.uid()) AND (list_members.role = ANY (ARRAY['owner'::public.list_role,
    'editor'::public.list_role])))))));

